#!/usr/bin/env python3
"""Generate a random catering invoice and its decomposition file.

This example has no link with any real event. Products are drawn at random
from the Agribalyse database, and so are the meals, guest numbers, portion
sizes and matching confidences. Its only purpose is to show that the tools
run on any food inventory laid out in the expected format.

Every feature of the decomposition format is exercised at least once: the five
mass estimation methods, single and multiple Agribalyse candidates, a
confidence and a mass_cv set per candidate, and a mass_cv set per component.

Run from the repository root (the output is reproducible, the seed is fixed):

    python examples/random_products/make_random_example.py
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from agribalyse_autoderive import load_agribalyse  # noqa: E402

AGRIBALYSE = ROOT / 'data' / 'AGRIBALYSE3.2_Tableur produits alimentaires_PublieAOUT25.xlsx'
OUT_DIR = Path(__file__).resolve().parent
SEED = 2026

GROUPS = ['Seminar day 1', 'Seminar day 2', 'Field trip']
MEALS = ['Breakfast', 'Coffee break', 'Lunch', 'Dinner']
CONFIDENCES = ['HIGH', 'MEDIUM', 'LOW']
METHODS = ['mass_g_per_person', 'pieces', 'volume', 'total_mass_kg', 'per_unit']


def quote(text: str) -> str:
    return '"' + str(text).replace('"', "'") + '"'


def component(rng, agri, guests):
    """One elementary product: a random reference, possibly with alternative
    candidates from the same Agribalyse sub-group, and a random mass method."""
    ref = agri.sample(1, random_state=int(rng.integers(1e9))).iloc[0]
    same = agri[(agri['SousGroupe'] == ref['SousGroupe']) & (agri['Code_AGB'] != ref['Code_AGB'])]
    n_alt = int(rng.integers(0, min(2, len(same)) + 1))
    codes = [ref['Code_AGB']] + list(same.sample(n_alt, random_state=int(rng.integers(1e9)))['Code_AGB'])
    method = METHODS[int(rng.integers(len(METHODS)))]
    lines = [f'      - name: {quote(ref["LCI_Name"])}']
    if method == 'mass_g_per_person':
        lines.append(f'        mass_g_per_person: {int(rng.integers(20, 250))}')
    elif method == 'pieces':
        lines.append(f'        pieces_per_person: {int(rng.integers(1, 4))}')
        lines.append(f'        mass_per_piece_g: {int(rng.integers(15, 120))}')
    elif method == 'volume':
        lines.append(f'        volume_mL_per_person: {int(rng.integers(100, 300))}')
        lines.append(f'        density_kg_L: {rng.choice([1.0, 1.03, 1.04])}')
    elif method == 'total_mass_kg':
        lines.append(f'        total_mass_kg: {round(float(rng.uniform(0.5, 0.15 * guests)), 2)}')
    else:
        lines.append(f'        mass_per_unit_kg: {rng.choice([0.25, 0.5, 0.75, 1.0])}')
        lines.append(f'        nb_units: {int(rng.integers(2, 12))}')
    confidence = CONFIDENCES[int(rng.integers(3))]
    if len(codes) > 1 and rng.random() < 0.4:
        # Confidence is about the match, so it may differ between candidates.
        lines.append('        agribalyse_codes:')
        for code in codes:
            extra = f', mass_cv: {round(float(rng.uniform(0.1, 0.6)), 2)}' if rng.random() < 0.3 else ''
            lines.append(f'          - {{code: "{code}", confidence: {CONFIDENCES[int(rng.integers(3))]}{extra}}}')
    else:
        # Codes are quoted: YAML would read 9341_1 as the integer 93411.
        lines.append(f'        agribalyse_codes: [{", ".join(quote(c) for c in codes)}]')
        lines.append(f'        confidence: {confidence}')
        if rng.random() < 0.15:
            lines.append(f'        mass_cv: {round(float(rng.uniform(0.1, 0.8)), 2)}')
    lines.append(f'        source: "Random example, method {method}"')
    return lines


def main():
    rng = np.random.default_rng(SEED)
    agri = load_agribalyse(str(AGRIBALYSE))
    invoice, yml = [], [
        '# decomposition.yml - random example',
        '# Generated by make_random_example.py (seed %d). No link with any real event:' % SEED,
        '# products, guests, portions and confidences are all drawn at random.',
        '',
        'items:',
    ]
    for group in GROUPS:
        for meal in rng.choice(MEALS, size=int(rng.integers(2, 4)), replace=False):
            item = f'{meal} menu'
            guests = int(rng.integers(15, 80))
            price = round(float(rng.uniform(4, 30)), 2)
            invoice.append({'Group': group, 'MealType': meal, 'Item': item, 'Qty': guests,
                            'Unit': 'cover', 'UnitPriceHT': price, 'TotalPriceTTC': round(price * guests * 1.1, 2),
                            'NbGuests': guests, 'Notes': 'Random example'})
            yml += ['', f'  - group: {quote(group)}', f'    meal_type: {quote(meal)}',
                    f'    invoice_item: {quote(item)}', '    components:']
            for _ in range(int(rng.integers(2, 6))):
                yml += component(rng, agri, guests)
    pd.DataFrame(invoice).to_excel(OUT_DIR / 'invoice.xlsx', index=False)
    (OUT_DIR / 'decomposition.yml').write_text('\n'.join(yml) + '\n', encoding='utf-8')
    print(f'{len(invoice)} invoice lines written to {OUT_DIR}')


if __name__ == '__main__':
    main()
